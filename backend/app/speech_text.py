def fmt_date(iso: str | None, lang: str) -> str:
    if not iso:
        return ""
    d = date.fromisoformat(iso)
    return f"{d.day} {MONTHS[lang][d.month - 1]}"


def readback(lang: str, name: str | None, visit_type: str, r: dict, flags: list, missing: list) -> str:
    t, parts = T[lang], []
    if name:
        parts.append(name)
    if visit_type == "ANC":
        if r.get("gestation_months"):
            parts.append(t["months_preg"].format(n=r["gestation_months"]))
        if r.get("bp_systolic"):
            parts.append(t["bp"].format(s=r["bp_systolic"], d=r.get("bp_diastolic") or ""))
        elif r.get("bp_status_spoken"):
            parts.append(t["bp_word"].format(w=r["bp_status_spoken"]))
        if r.get("hb") is not None:
            parts.append(t["hb"].format(v=r["hb"]))
        if r.get("ifa_tablets_given"):
            parts.append(t["ifa"].format(n=r["ifa_tablets_given"]))
        if r.get("calcium_tablets_given"):
            parts.append(t["calcium"].format(n=r["calcium_tablets_given"]))
        if r.get("td_dose"):
            parts.append(t["td"].format(v=r["td_dose"]))
    if visit_type == "HBNC":
        if r.get("baby_age_days") is not None:
            parts.append(t["baby_days"].format(n=r["baby_age_days"]))
        if r.get("weight_kg"):
            parts.append(t["weight"].format(v=r["weight_kg"]))
        if r.get("temperature_c"):
            parts.append(t["temp"].format(v=r["temperature_c"]))
        if r.get("breastfeeding_ok") is not None:
            parts.append(t["bf_ok"] if r["breastfeeding_ok"] else t["bf_no"])
    if visit_type == "IMMUNISATION" and r.get("vaccines_given"):
        parts.append(t["vaccines"].format(v=", ".join(r["vaccines_given"])))
    complaints = [c for c in r.get("complaints", [])
                  if not (c == "not feeding" and r.get("breastfeeding_ok") is False)]  # already said
    if complaints:
        names = [COMPLAINT_NAMES[lang].get(c, c) for c in complaints]
        parts.append(t["complaints"].format(v=", ".join(names)))
    if r.get("next_visit_date"):
        parts.append(t["next"].format(d=fmt_date(r["next_visit_date"], lang)))
    text = ". ".join(parts) + "."
    if flags:
        text += " " + t["flag"].format(v=", ".join(dict.fromkeys(f["labels"][lang] for f in flags)))
    if missing:
        text += " " + t["missing"].format(v=", ".join(FIELD_NAMES[lang].get(m, m) for m in missing))
    return text + " " + t["ask"]


def is_yes(transcript: str) -> bool:
    words = {w.strip(".,!?।").lower() for w in transcript.split()}
    return bool(words & YES_WORDS) and len(words) <= 4
